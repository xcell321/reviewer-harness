// lib/adapters/render.js — the ONE shared instruction-file renderer.
//
// Every adapter renders the same shape: header, generated-file notice,
// optional problem section, numbered-or-bulleted rules, skill sections.
// The only per-adapter difference is the list marker, chosen here by
// `numbered` (true → `1. …`, false → `- …`). Adapters are thin wrappers
// over this function; see lib/adapters/claude.js, gemini.js, opencode.js.

export function renderInstructions(config, { numbered }) {
  return [
    `# ${config.name} — harness instructions`,
    ``,
    `> This file is generated by your harness. Do not edit it directly —`,
    `> change harness.config.json and sync again.`,
    ``,
    // The "why" — the problem the rules solve, synced along with them.
    ...(config.problem
      ? [`## The problem this solves`, ``, config.problem, ``]
      : []),
    `## Rules — the AI must never break these`,
    ``,
    ...config.rules.map((rule, i) =>
      numbered ? `${i + 1}. ${rule}` : `- ${rule}`
    ),
    ``,
    // Skills (Lesson 4): rendered after the rules.
    ...(config.skillSections ?? []).flatMap((s) => [s, ``]),
  ].join("\n");
}
