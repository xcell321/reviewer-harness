// lib/adapters/opencode.js — ADAPTER for OpenCode.
//
// The adapter pattern is the heart of a universal harness: the master
// spec is ONE, but every runtime (OpenCode, Claude, Gemini, ...) has
// its own instruction-file format. The adapter translates from the
// master spec into the runtime's format.
//
// OpenCode reads `.opencode/instructions.md` in your project.

export function targetFile() {
  return ".opencode/instructions.md";
}

export function renderInstructions(config) {
  const lines = [];
  lines.push(`# ${config.name} — harness instructions`);
  lines.push(``);
  lines.push(
    `> This file is generated by your harness. Do not edit it directly —`,
    `> change harness.config.json and sync again.`
  );
  lines.push(``);
  // The "why" — the problem the rules solve, synced along with them.
  if (config.problem) {
    lines.push(`## The problem this solves`);
    lines.push(``);
    lines.push(config.problem);
    lines.push(``);
  }
  lines.push(`## Rules — the AI must never break these`);
  lines.push(``);
  config.rules.forEach((rule, i) => {
    lines.push(`${i + 1}. ${rule}`);
  });
  lines.push(``);
  // Skills (Lesson 4): rendered after the rules.
  for (const section of config.skillSections ?? []) {
    lines.push(section);
    lines.push(``);
  }
  return lines.join("\n");
}
