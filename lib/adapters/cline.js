// lib/adapters/cline.js — ADAPTER for Cline.
//
// Cline reads .clinerules in the project root.
// .clinerules is usually plainer — no big headers, straight to the
// rules. The adapter adjusts the style per runtime.

export function targetFile() {
  return ".clinerules";
}

export function renderInstructions(config) {
  return [
    `# Rules (generated by ${config.name} — do not edit directly)`,
    ``,
    // The "why" — plain style too, since .clinerules is simpler.
    ...(config.problem ? [`# The problem: ${config.problem}`, ``] : []),
    ...config.rules.map((rule) => `- ${rule}`),
    ``,
    // Skills (Lesson 4): rendered after the rules.
    ...(config.skillSections ?? []).flatMap((s) => [s, ``]),
  ].join("\n");
}
