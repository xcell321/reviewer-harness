// lib/adapters/claude.js — ADAPTER for Claude Code.
//
// Claude Code reads CLAUDE.md in the project root at every session.
// It is the best-known instruction file among AI coding tools.

export function targetFile() {
  return "CLAUDE.md";
}

export function renderInstructions(config) {
  return [
    `# ${config.name} — harness instructions`,
    ``,
    `> This file is generated by your harness. Do not edit it directly —`,
    `> change harness.config.json and sync again.`,
    ``,
    // The "why" — the problem the rules solve, synced along with them.
    ...(config.problem
      ? [`## The problem this solves`, ``, config.problem, ``]
      : []),
    `## Rules — the AI must never break these`,
    ``,
    ...config.rules.map((rule, i) => `${i + 1}. ${rule}`),
    ``,
    // Skills (Lesson 4): rendered after the rules.
    ...(config.skillSections ?? []).flatMap((s) => [s, ``]),
  ].join("\n");
}
